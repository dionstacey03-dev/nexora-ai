import React, { useState } from 'react';
import {
  FileCode,
  Copy,
  Check,
  Download,
  Eye,
  Code,
  Sparkles,
  Loader2,
  Save,
  BookOpen,
  Terminal,
} from 'lucide-react';
import { useProjects } from '../../context/ProjectContext';

export const ReadmeStudio: React.FC = () => {
  const { projects, currentProject, selectProject, generateReadme, updateProject, showToast, setActiveTab } =
    useProjects();

  const activeProject = currentProject || (projects.length > 0 ? projects[0] : null);

  const [mode, setMode] = useState<'preview' | 'raw'>('preview');
  const [copied, setCopied] = useState(false);
  const [isRegenerating, setIsRegenerating] = useState(false);

  // Markdown content
  const [markdownContent, setMarkdownContent] = useState<string>(
    activeProject?.readmeMarkdown || '# README\n\nGenerated by NEXORA AI.'
  );

  // Sync markdown content when project changes
  React.useEffect(() => {
    if (activeProject?.readmeMarkdown) {
      setMarkdownContent(activeProject.readmeMarkdown);
    }
  }, [activeProject?.id]);

  if (!activeProject) {
    return (
      <div className="max-w-4xl mx-auto px-4 py-12 text-center space-y-4">
        <div className="w-16 h-16 rounded-3xl bg-violet-500/10 text-violet-500 mx-auto flex items-center justify-center">
          <FileCode className="w-8 h-8" />
        </div>
        <h2 className="text-xl font-bold text-slate-900 dark:text-white">No Projects Available</h2>
        <p className="text-xs text-slate-500 max-w-sm mx-auto">
          Synthesize an architecture with the AI generator first to generate documentation.
        </p>
        <button
          onClick={() => setActiveTab('generator')}
          className="px-4 py-2.5 rounded-xl text-xs font-bold text-white bg-violet-600 hover:bg-violet-500 transition-all inline-flex items-center gap-1.5 cursor-pointer"
        >
          <Sparkles className="w-3.5 h-3.5" />
          <span>Launch Generator</span>
        </button>
      </div>
    );
  }

  const handleCopyMarkdown = () => {
    navigator.clipboard.writeText(markdownContent);
    setCopied(true);
    showToast('README markdown copied to clipboard!', 'success');
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadReadme = () => {
    const blob = new Blob([markdownContent], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'README.md';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    showToast('Downloaded README.md', 'success');
  };

  const handleRegenerateWithGemini = async () => {
    setIsRegenerating(true);
    try {
      const generated = await generateReadme(activeProject);
      setMarkdownContent(generated);
      updateProject(activeProject.id, { readmeMarkdown: generated });
      showToast('README documentation regenerated with Gemini AI!', 'success');
    } catch (e) {
      console.error(e);
      showToast('Failed to regenerate README', 'error');
    } finally {
      setIsRegenerating(false);
    }
  };

  const handleSaveToProject = () => {
    updateProject(activeProject.id, { readmeMarkdown: markdownContent });
    showToast('Saved custom README changes to project!', 'success');
  };

  // Simple Markdown renderer for Preview mode
  const renderSimpleMarkdown = (md: string) => {
    const lines = md.split('\n');
    let inCodeBlock = false;
    let codeBlockContent: string[] = [];
    const elements: React.ReactNode[] = [];

    lines.forEach((line, idx) => {
      if (line.startsWith('```')) {
        if (inCodeBlock) {
          elements.push(
            <pre
              key={`code-${idx}`}
              className="p-4 rounded-2xl bg-slate-900 text-slate-100 font-mono text-xs overflow-x-auto my-3 border border-slate-800"
            >
              <code>{codeBlockContent.join('\n')}</code>
            </pre>
          );
          codeBlockContent = [];
          inCodeBlock = false;
        } else {
          inCodeBlock = true;
        }
        return;
      }

      if (inCodeBlock) {
        codeBlockContent.push(line);
        return;
      }

      if (line.startsWith('# ')) {
        elements.push(
          <h1 key={idx} className="text-2xl font-extrabold text-slate-900 dark:text-white mt-6 mb-3 border-b pb-2 border-slate-200 dark:border-white/10">
            {line.replace('# ', '')}
          </h1>
        );
      } else if (line.startsWith('## ')) {
        elements.push(
          <h2 key={idx} className="text-lg font-bold text-slate-900 dark:text-white mt-5 mb-2 flex items-center gap-2">
            <span className="w-1.5 h-1.5 rounded-full bg-violet-500" />
            {line.replace('## ', '')}
          </h2>
        );
      } else if (line.startsWith('### ')) {
        elements.push(
          <h3 key={idx} className="text-sm font-bold text-slate-800 dark:text-slate-200 mt-4 mb-1">
            {line.replace('### ', '')}
          </h3>
        );
      } else if (line.startsWith('> ')) {
        elements.push(
          <blockquote
            key={idx}
            className="p-3 my-2 rounded-xl border-l-4 border-violet-500 bg-violet-500/5 text-slate-700 dark:text-slate-300 text-xs italic"
          >
            {line.replace('> ', '')}
          </blockquote>
        );
      } else if (line.startsWith('* ') || line.startsWith('- ')) {
        elements.push(
          <li key={idx} className="text-xs text-slate-700 dark:text-slate-300 ml-4 list-disc my-0.5">
            {line.replace(/^(\*|-)\s+/, '')}
          </li>
        );
      } else if (line.trim() === '') {
        elements.push(<div key={idx} className="h-2" />);
      } else {
        elements.push(
          <p key={idx} className="text-xs text-slate-700 dark:text-slate-300 leading-relaxed my-1">
            {line}
          </p>
        );
      }
    });

    return elements;
  };

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-6 space-y-6 animate-fade-in">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-violet-500/10 dark:bg-violet-500/20 text-violet-600 dark:text-violet-300 border border-violet-500/20 text-xs font-semibold">
            <FileCode className="w-3.5 h-3.5" />
            <span>GitHub Documentation Studio</span>
          </div>
          <h1 className="text-2xl sm:text-3xl font-extrabold tracking-tight text-slate-900 dark:text-white mt-1">
            README Studio
          </h1>
          <p className="text-xs sm:text-sm text-slate-500 dark:text-slate-400">
            Generate, edit, preview, and download production-grade GitHub repository documentation.
          </p>
        </div>

        {/* Project Switcher */}
        <div className="flex items-center gap-2">
          <span className="text-xs font-mono text-slate-400">Project:</span>
          <select
            value={activeProject.id}
            onChange={(e) => selectProject(e.target.value)}
            className="px-3 py-2 rounded-xl text-xs sm:text-sm font-semibold bg-slate-100 dark:bg-slate-900 border border-slate-200 dark:border-white/10 text-slate-900 dark:text-white cursor-pointer focus:ring-2 focus:ring-violet-500"
          >
            {projects.map((p) => (
              <option key={p.id} value={p.id}>
                {p.name}
              </option>
            ))}
          </select>
        </div>
      </div>

      {/* Control Bar */}
      <div className="p-3 rounded-2xl glass-surface border border-slate-200/80 dark:border-white/10 shadow-sm flex flex-wrap items-center justify-between gap-3">
        {/* Preview vs Raw Editor Toggle */}
        <div className="flex items-center p-1 rounded-xl bg-slate-100 dark:bg-slate-900 border border-slate-200 dark:border-white/10">
          <button
            onClick={() => setMode('preview')}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold transition-all cursor-pointer ${
              mode === 'preview'
                ? 'bg-violet-600 text-white shadow-xs'
                : 'text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-white'
            }`}
          >
            <Eye className="w-3.5 h-3.5" />
            <span>Markdown Preview</span>
          </button>
          <button
            onClick={() => setMode('raw')}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold transition-all cursor-pointer ${
              mode === 'raw'
                ? 'bg-violet-600 text-white shadow-xs'
                : 'text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-white'
            }`}
          >
            <Code className="w-3.5 h-3.5" />
            <span>Raw Markdown</span>
          </button>
        </div>

        {/* Action Buttons */}
        <div className="flex items-center gap-2">
          <button
            onClick={handleRegenerateWithGemini}
            disabled={isRegenerating}
            className="flex items-center gap-1.5 px-3.5 py-1.5 rounded-xl text-xs font-semibold text-violet-600 dark:text-violet-300 bg-violet-500/10 hover:bg-violet-500/20 border border-violet-500/20 transition-all cursor-pointer disabled:opacity-50"
          >
            {isRegenerating ? (
              <Loader2 className="w-3.5 h-3.5 animate-spin" />
            ) : (
              <Sparkles className="w-3.5 h-3.5" />
            )}
            <span>Regenerate with Gemini</span>
          </button>

          {mode === 'raw' && (
            <button
              onClick={handleSaveToProject}
              className="flex items-center gap-1.5 px-3.5 py-1.5 rounded-xl text-xs font-semibold text-emerald-600 dark:text-emerald-400 bg-emerald-500/10 hover:bg-emerald-500/20 border border-emerald-500/20 transition-all cursor-pointer"
            >
              <Save className="w-3.5 h-3.5" />
              <span>Save Changes</span>
            </button>
          )}

          <button
            onClick={handleCopyMarkdown}
            className="flex items-center gap-1.5 px-3.5 py-1.5 rounded-xl text-xs font-semibold text-slate-700 dark:text-slate-200 bg-slate-100 dark:bg-white/10 hover:bg-slate-200 transition-all cursor-pointer"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-500" />
                <span className="text-emerald-500">Copied!</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span>Copy</span>
              </>
            )}
          </button>

          <button
            onClick={handleDownloadReadme}
            className="flex items-center gap-1.5 px-3.5 py-1.5 rounded-xl text-xs font-bold text-white bg-violet-600 hover:bg-violet-500 shadow-xs transition-all cursor-pointer"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download README.md</span>
          </button>
        </div>
      </div>

      {/* Editor & Preview Workspace */}
      <div className="rounded-3xl glass-surface border border-slate-200/80 dark:border-white/10 shadow-xl overflow-hidden">
        {mode === 'preview' ? (
          <div className="p-6 sm:p-10 max-h-[650px] overflow-y-auto space-y-2">
            {renderSimpleMarkdown(markdownContent)}
          </div>
        ) : (
          <div className="p-4 sm:p-6 bg-slate-950">
            <textarea
              rows={22}
              value={markdownContent}
              onChange={(e) => setMarkdownContent(e.target.value)}
              className="w-full font-mono text-xs sm:text-sm bg-transparent text-slate-200 focus:outline-hidden resize-none leading-relaxed"
            />
          </div>
        )}
      </div>
    </div>
  );
};
